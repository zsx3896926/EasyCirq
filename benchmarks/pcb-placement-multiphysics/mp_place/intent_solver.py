def _as_placement(payload: Dict) -> Placement:
    """Convert a pipeline report ``placement`` payload back into a Placement."""
    return {
        ref: (float(coord[0]), float(coord[1]), int(coord[2]))
        for ref, coord in payload.items()
    }


def benchmark(
    names: Optional[Sequence[str]] = None,
    seeds: Sequence[int] = (0, 1),
    steps: int = DEFAULT_STEPS,
    pipeline_steps: int = 800,
) -> Dict:
    """Run the P3.6 benchmark (intent-reference -> plan vs unconstrained pipeline).

    For every ``(template, seed)`` the reference layout is a hard-feasible
    ``random_feasible_placement`` (deterministic per template/seed), the intent
    is built from it, and the planner is seeded with the same ``seed``.  The
    pipeline baseline is :func:`mp_place.pipeline.run_pipeline` with
    ``budget_steps=pipeline_steps``.

    Returns a dict with ``config``, per-run ``rows`` and an ``aggregate`` block
    (CCG satisfaction rate, hard-feasibility rate, mean v2 truth and the
    intent-violation count of the pipeline baseline).
    """
    from .physics_v2 import PhysicsSimulatorV2
    from .pipeline import run_pipeline
    from .templates import instantiate, template_names

    template_names_ = list(template_names() if names is None else names)
    rows: List[Dict] = []
    for name in template_names_:
        for seed in seeds:
            seed = int(seed)
            sc = instantiate(name, seed=seed)
            reference = random_feasible_placement(
                sc, random.Random(f"intent-benchmark-ref:{name}:{seed}")
            )
            intent = build_intent(sc, reference)
            plan, stats = plan_from_intent(
                sc,
                intent,
                cost=ProxyObjective(sc).cost,
                seed=seed,
                steps=steps,
            )
            truth = PhysicsSimulatorV2(sc, seed=seed)
            plan_truth = float(truth.score(plan))
            reference_truth = float(truth.score(reference))
            pipeline_report = run_pipeline(sc, budget_steps=pipeline_steps, seed=seed)
            pipeline_placement = _as_placement(pipeline_report["placement"])
            pipeline_truth = float(pipeline_report["truth_v2"])
            pipeline_ccg = len(intent_violations(sc, pipeline_placement, intent))
            hard = list(hard_violations(sc, plan))
            rows.append(
                {
                    "template": name,
                    "seed": seed,
                    "ccg_initial": int(stats["ccg_initial"]),
                    "ccg_final": int(stats["ccg_final"]),
                    "hard_feasible": not hard,
                    "truth_v2_plan": plan_truth,
                    "truth_v2_pipeline": pipeline_truth,
                    "truth_v2_reference": reference_truth,
                    "truth_vs_pipeline_pct": (
                        100.0 * (plan_truth - pipeline_truth) / pipeline_truth
                        if pipeline_truth
                        else 0.0
                    ),
                    "pipeline_ccg": int(pipeline_ccg),
                    "proxy_cost_initial": float(stats["cost_initial"]),
                    "proxy_cost_final": float(stats["cost_final"]),
                    "moves": int(stats["moves"]),
                    "moves_accepted": int(stats["moves_accepted"]),
                }
            )

    run_count = len(rows)
    hard_count = sum(1 for row in rows if row["hard_feasible"])
    ccg_zero = sum(1 for row in rows if row["ccg_final"] == 0)
    mean = lambda key: sum(row[key] for row in rows) / run_count if run_count else 0.0
    aggregate = {
        "runs": run_count,
        "templates": len(template_names_),
        "seeds": [int(s) for s in seeds],
        "ccg_zero_rate": ccg_zero / run_count if run_count else 0.0,
        "hard_feasible_rate": hard_count / run_count if run_count else 0.0,
        "mean_ccg_initial": mean("ccg_initial"),
        "mean_ccg_final": mean("ccg_final"),
        "mean_truth_v2_plan": mean("truth_v2_plan"),
        "mean_truth_v2_pipeline": mean("truth_v2_pipeline"),
        "mean_truth_v2_reference": mean("truth_v2_reference"),
        "mean_truth_vs_pipeline_pct": mean("truth_vs_pipeline_pct"),
        "mean_pipeline_ccg": mean("pipeline_ccg"),
        "mean_proxy_cost_initial": mean("proxy_cost_initial"),
        "mean_proxy_cost_final": mean("proxy_cost_final"),
        "steps": int(steps),
        "pipeline_steps": int(pipeline_steps),
    }
    return {"config": {"steps": int(steps), "pipeline_steps": int(pipeline_steps)},
            "rows": rows, "aggregate": aggregate}


def _format_markdown(result: Dict) -> str:
    """Render :func:`benchmark` output as the markdown table used in the docstring."""
    lines = [
        "| template | seed | CCG init -> final | hard | truth_v2 plan | truth_v2 pipeline | plan vs pipeline | pipeline CCG |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in result["rows"]:
        lines.append(
            "| {template} | {seed} | {ccg_initial} -> {ccg_final} | {hard_feasible} | "
            "{truth_v2_plan:.3f} | {truth_v2_pipeline:.3f} | {truth_vs_pipeline_pct:+.1f}% | "
            "{pipeline_ccg} |".format(**row)
        )
    agg = result["aggregate"]
    lines.append("")
    lines.append(
        "Aggregate over {runs} runs ({templates} templates x seeds {seeds}): CCG satisfaction "
        "rate {ccg_zero_rate:.1%}, hard-feasibility rate {hard_feasible_rate:.1%}; "
        "mean truth_v2 plan {mean_truth_v2_plan:.3f} vs pipeline {mean_truth_v2_pipeline:.3f} "
        "({mean_truth_vs_pipeline_pct:+.1f}%), reference {mean_truth_v2_reference:.3f}; "
        "pipeline leaves {mean_pipeline_ccg:.1f} CCG violations on average.".format(**agg)
    )
    return "\n".join(lines)


def main(argv: Optional[Sequence[str]] = None) -> int:
    """``python -m mp_place.intent_solver`` -> print the benchmark table."""
    import argparse
    import json

    parser = argparse.ArgumentParser(description="P3.6 intent-constrained planner benchmark")
    parser.add_argument("--steps", type=int, default=DEFAULT_STEPS)
    parser.add_argument("--pipeline-steps", type=int, default=800)
    parser.add_argument("--seeds", default="0,1")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    seeds = tuple(int(item) for item in str(args.seeds).split(",") if item.strip())
    result = benchmark(steps=args.steps, pipeline_steps=args.pipeline_steps, seeds=seeds)
    if args.json:
        print(json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True))
    else:
        print(_format_markdown(result))
    return 0



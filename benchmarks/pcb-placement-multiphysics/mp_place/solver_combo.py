"""P2.17 solver_v3 + route-aware objective combination experiment.

P2.16 showed ``solver_v3`` (constructive start + 3-trajectory portfolio) gets a
much better proxy cost than ``solver_v2`` but a worse offline-router completion:
stronger pure-proxy optimisation produces more compact layouts.  This module
tests the natural fix: run **solver_v3 on the route-aware objective**
(:class:`mp_place.route_cost.RouteAwareObjective` with the fixed P2.8 weight
``w_route=2.0``) and compare it with the four/five relevant combinations on
8 templates x seeds 0/1, same total move budget ``steps=800``:

=====================  =====================================================
group                  placement search
=====================  =====================================================
``v2_proxy``           solver_v2, plain ProxyObjective (P1/P2 baseline)
``v3_proxy``           solver_v3, plain ProxyObjective (P2.16 portfolio)
``v2_route_aware``     solver_v2, RouteAwareObjective(w=2.0) (P2.8)
``v3_route_aware``     solver_v3, RouteAwareObjective(w=2.0)  <- combination
``route_aware_repair`` route_aware solve + ``route_opt.repair_routes`` (P2.5
                       post-hoc repair; ``repair_routes`` re-solves with
                       solver_v2 internally, so this is the practical repair
                       path available without changing module interfaces)
=====================  =====================================================

Every placement is scored on: proxy cost (plain ``ProxyObjective``, comparable
across groups), ``truth_v2`` (``PhysicsSimulatorV2``), offline router completion
(1 mm / 2-layer ``GridRouter``), hard feasibility and wall time.  The report
(``report_solver_combo.{md,json}``, generated by ``python -m mp_place.solver_combo``)
answers whether ``v3 + route_aware`` simultaneously keeps the proxy-cost gain and
recovers completion, and gives a deterministic recommended combination.

Tests cover determinism, hard feasibility, budget equivalence (same steps for all
solver groups; ``max_routes`` cap for the repair group) and an 8-template smoke
run.  Offline only: no DRC/EDA/network; the router/truth models are surrogates.

Recorded result (8 templates x seeds 0/1, steps=800, means; baseline = v2/proxy)::

    group                  proxy cost   cost Δ     truth_v2   truth Δ   completion   fully routed   time/run
    v2_proxy                 3.4318      +0.00%     2.0001     +0.00%     0.9019         6/16         0.173 s
    v3_proxy                 3.1145      -9.25%     1.8422     -7.90%     0.7326         2/16         0.261 s
    v2_route_aware           3.4292      -0.08%     2.0627     +3.13%     0.9755        14/16         0.446 s
    v3_route_aware           3.3416      -2.63%     2.0639     +3.19%     0.9100         8/16         0.504 s
    route_aware_repair       3.4359      +0.12%     1.9861     -0.70%     1.0000        16/16         1.147 s

**Is v3 + route_aware a two-win? Not strictly.**  It does fix the P2.16 problem
partially: completion recovers from 0.7326 (v3/proxy) to 0.9100 while proxy cost
stays -2.63% vs baseline.  But it is still 0.0655 below v2/route_aware's
completion and its truth_v2 is +3.19%; the strict "two wins" check therefore
fails.  Recommended combination from the deterministic rule: for completion-first
use ``route_aware_repair`` (1.0000 completion, -0.70% truth, but 6.6x runtime);
without router calls use ``v2_route_aware`` (0.9755); if proxy cost is the
priority use ``v3_route_aware`` (-2.63%, completion 0.9100).
"""

from __future__ import annotations

import argparse
import json
import math
import pathlib
import time
from typing import Dict, List, Optional, Sequence, Tuple

from . import route_cost, route_opt, solver_v2, solver_v3
from .model import Placement, Scenario, hard_violations
from .objective import ProxyObjective
from .physics_v2 import PhysicsSimulatorV2
from .router import GridRouter
from .templates import instantiate, template_names

REPORT_MD = "report_solver_combo.md"
REPORT_JSON = "report_solver_combo.json"
PROJECT_ROOT = pathlib.Path(__file__).resolve().parent.parent

DEFAULT_STEPS = 800
ROUTE_AWARE_W = 2.0
MAX_ROUTES = 60
ROUTER_GRID_MM = 1.0
ROUTER_LAYERS = 2

GROUP_ORDER: Tuple[str, ...] = (
    "v2_proxy",
    "v3_proxy",
    "v2_route_aware",
    "v3_route_aware",
    "route_aware_repair",
)
GROUP_LABELS: Dict[str, str] = {
    "v2_proxy": "v2 / proxy",
    "v3_proxy": "v3 / proxy",
    "v2_route_aware": f"v2 / route_aware(w={ROUTE_AWARE_W})",
    "v3_route_aware": f"v3 / route_aware(w={ROUTE_AWARE_W})",
    "route_aware_repair": f"route_aware + post-hoc repair (max_routes={MAX_ROUTES})",
}

#: group -> (solver, objective_mode, uses_posthoc_repair)
GROUPS: Dict[str, Dict[str, object]] = {
    "v2_proxy": {"solver": "v2", "objective": "proxy", "repair": False},
    "v3_proxy": {"solver": "v3", "objective": "proxy", "repair": False},
    "v2_route_aware": {"solver": "v2", "objective": "route_aware", "repair": False},
    "v3_route_aware": {"solver": "v3", "objective": "route_aware", "repair": False},
    "route_aware_repair": {"solver": "v2", "objective": "route_aware", "repair": True},
}


def _mean(values: Sequence[float]) -> float:
    return sum(values) / len(values) if values else 0.0


def _std(values: Sequence[float]) -> float:
    if len(values) < 2:
        return 0.0
    mean = _mean(values)
    return math.sqrt(sum((value - mean) ** 2 for value in values) / len(values))


def build_objective(scenario: Scenario, objective_mode: str, proxy: Optional[ProxyObjective] = None):
    """Return ``(cost_fn, proxy)`` for ``"proxy"`` or ``"route_aware"``."""
    proxy = proxy if proxy is not None else ProxyObjective(scenario)
    if objective_mode == "proxy":
        return proxy.cost, proxy
    if objective_mode == "route_aware":
        objective = route_cost.RouteAwareObjective(
            scenario, base=proxy, w_route=ROUTE_AWARE_W, profile=None
        )
        return objective.cost, proxy
    raise ValueError(f"unknown objective mode {objective_mode!r}")


def _route_completion(scenario: Scenario, placement: Placement) -> float:
    result = GridRouter(scenario, grid_mm=ROUTER_GRID_MM, layers=ROUTER_LAYERS).route(placement)
    return float(result.completion)


def evaluate_group(
    scenario: Scenario,
    group: str,
    seed: int = 0,
    steps: int = DEFAULT_STEPS,
) -> Dict[str, object]:
    """Run one combination group on one scenario/seed and measure all metrics."""
    config = GROUPS.get(group)
    if config is None:
        raise KeyError(f"unknown combo group {group!r}; known: {sorted(GROUPS)}")
    seed = int(seed)
    steps = max(0, int(steps))
    proxy = ProxyObjective(scenario)
    cost_fn, _proxy = build_objective(scenario, str(config["objective"]), proxy=proxy)
    started = time.perf_counter()
    solver_stats: Dict[str, object] = {}
    if bool(config["repair"]):
        placement, truth, route_result, repair_stats = route_opt.repair_routes(
            scenario, cost_fn, seed=seed, steps=steps, max_routes=MAX_ROUTES
        )
        completion = float(route_result.completion)
        solver_stats = dict(repair_stats)
        attempts = int(repair_stats.get("routes_calls", 0))
        repair_used = True
    else:
        if str(config["solver"]) == "v3":
            placement, _objective_cost, solver_stats = solver_v3.solve_v3(
                scenario, cost_fn, seed=seed, steps=steps
            )
        else:
            placement, _objective_cost, solver_stats = solver_v2.solve(
                scenario, cost_fn, seed=seed, steps=steps
            )
        completion = _route_completion(scenario, placement)
        truth = float(PhysicsSimulatorV2(scenario, seed=seed).score(placement))
        repair_used = False
    runtime = time.perf_counter() - started
    proxy_cost = float(proxy.cost(placement))
    feasible = not hard_violations(scenario, placement)
    return {
        "group": group,
        "label": GROUP_LABELS[group],
        "template": scenario.name,
        "seed": seed,
        "steps": steps,
        "proxy_cost": proxy_cost,
        "truth_v2": truth,
        "completion": completion,
        "feasible": feasible,
        "runtime_s": runtime,
        "objective_cost": float(cost_fn(placement)),
        "attempts": attempts if repair_used else int(solver_stats.get("attempts", 0)),
        "routes_calls": int(solver_stats.get("routes_calls", 0)) if repair_used else 0,
        "winner": solver_stats.get("winner"),
        "placement": placement,
        "solver_stats": solver_stats,
    }


def run_benchmark(
    names: Optional[Sequence[str]] = None,
    seeds: Sequence[int] = (0, 1),
    steps: int = DEFAULT_STEPS,
) -> Dict[str, object]:
    """Five-group combination benchmark on 8 templates x seeds."""
    template_names_list = list(template_names() if names is None else names)
    rows: List[Dict[str, object]] = []
    started = time.perf_counter()
    for name in template_names_list:
        for seed in seeds:
            scenario = instantiate(name, seed=int(seed))
            for group in GROUP_ORDER:
                result = evaluate_group(scenario, group, seed=int(seed), steps=steps)
                # Keep the JSON report compact: rows are metrics-only.
                row = {
                    key: value
                    for key, value in result.items()
                    if key not in {"placement", "solver_stats"}
                }
                rows.append(row)
                print(
                    f"[combo] {name} seed={seed} {group:18s}: "
                    f"proxy_cost={result['proxy_cost']:.4f} "
                    f"truth={result['truth_v2']:.4f} comp={result['completion']:.3f} "
                    f"feasible={result['feasible']} t={result['runtime_s']:.2f}s"
                )
    data: Dict[str, object] = {
        "schema": "mp_place.solver_combo.report/v1",
        "config": {
            "templates": template_names_list,
            "seeds": [int(seed) for seed in seeds],
            "steps": int(steps),
            "groups": {group: GROUP_LABELS[group] for group in GROUP_ORDER},
            "route_aware_weight": ROUTE_AWARE_W,
            "max_routes": MAX_ROUTES,
            "router": f"GridRouter(grid_mm={ROUTER_GRID_MM}, layers={ROUTER_LAYERS})",
            "truth": "PhysicsSimulatorV2",
        },
        "rows": rows,
        "aggregate": _aggregate(rows, template_names_list),
        "runtime_s": round(time.perf_counter() - started, 2),
    }
    data["conclusion"] = _conclude(data)
    return data


def _aggregate(
    rows: Sequence[Dict[str, object]],
    template_names_list: Sequence[str],
) -> Dict[str, object]:
    aggregate: Dict[str, object] = {
        "n_runs_per_group": len(rows) // len(GROUP_ORDER) if GROUP_ORDER else 0,
        "n_templates": len(template_names_list),
        "n_groups": len(GROUP_ORDER),
    }
    base_rows = [row for row in rows if row["group"] == "v2_proxy"]
    base_cost = _mean([float(row["proxy_cost"]) for row in base_rows])
    base_truth = _mean([float(row["truth_v2"]) for row in base_rows])
    base_completion = _mean([float(row["completion"]) for row in base_rows])
    aggregate["v2_proxy_reference"] = {
        "proxy_cost_mean": round(base_cost, 4),
        "truth_v2_mean": round(base_truth, 4),
        "completion_mean": round(base_completion, 4),
    }
    for group in GROUP_ORDER:
        subset = [row for row in rows if row["group"] == group]
        costs = [float(row["proxy_cost"]) for row in subset]
        truths = [float(row["truth_v2"]) for row in subset]
        completions = [float(row["completion"]) for row in subset]
        runtimes = [float(row["runtime_s"]) for row in subset]
        cost_mean = _mean(costs)
        truth_mean = _mean(truths)
        completion_mean = _mean(completions)
        aggregate[group] = {
            "proxy_cost_mean": round(cost_mean, 4),
            "proxy_cost_std": round(_std(costs), 4),
            "proxy_cost_delta_pct": round(
                100.0 * (cost_mean - base_cost) / base_cost, 2
            )
            if base_cost
            else 0.0,
            "truth_v2_mean": round(truth_mean, 4),
            "truth_delta_pct": round(100.0 * (truth_mean - base_truth) / base_truth, 2)
            if base_truth
            else 0.0,
            "completion_mean": round(completion_mean, 4),
            "completion_delta": round(completion_mean - base_completion, 4),
            "fully_routed": f"{sum(1 for value in completions if value >= 1.0)}/{len(subset)}",
            "hard_feasible_rate": round(
                sum(1 for row in subset if row["feasible"]) / len(subset), 4
            )
            if subset
            else 0.0,
            "runtime_s_mean": round(_mean(runtimes), 4),
        }
    per_template: Dict[str, object] = {}
    for name in template_names_list:
        block: Dict[str, object] = {}
        for group in GROUP_ORDER:
            subset = [
                row
                for row in rows
                if row["group"] == group and str(row["template"]) == name
            ]
            block[group] = {
                "proxy_cost_mean": round(
                    _mean([float(row["proxy_cost"]) for row in subset]), 4
                ),
                "truth_v2_mean": round(
                    _mean([float(row["truth_v2"]) for row in subset]), 4
                ),
                "completion_mean": round(
                    _mean([float(row["completion"]) for row in subset]), 4
                ),
                "fully_routed": f"{sum(1 for row in subset if float(row['completion']) >= 1.0)}/{len(subset)}",
            }
        base_cost = float(block["v2_proxy"]["proxy_cost_mean"])  # type: ignore[index]
        best_group = min(
            GROUP_ORDER,
            key=lambda group: (
                float(block[group]["proxy_cost_mean"]),  # type: ignore[index]
                -float(block[group]["completion_mean"]),  # type: ignore[index]
            ),
        )
        block["best_by_cost"] = best_group
        per_template[name] = block
    aggregate["per_template"] = per_template
    return aggregate


def _conclude(data: Dict[str, object]) -> Dict[str, object]:
    """Answer the P2.17 question and give a deterministic recommendation."""
    aggregate = data["aggregate"]  # type: ignore[index]
    base = aggregate["v2_proxy"]  # type: ignore[index]
    v3_ra = aggregate["v3_route_aware"]  # type: ignore[index]
    v2_ra = aggregate["v2_route_aware"]  # type: ignore[index]
    repair = aggregate["route_aware_repair"]  # type: ignore[index]
    v3_proxy = aggregate["v3_proxy"]  # type: ignore[index]

    base_completion = float(base["completion_mean"])  # type: ignore[index]
    base_truth = float(base["truth_v2_mean"])  # type: ignore[index]
    cost_gain = -float(v3_ra["proxy_cost_delta_pct"])  # type: ignore[index]
    completion_gain = float(v3_ra["completion_delta"])  # type: ignore[index]
    completion_vs_v2ra = float(v3_ra["completion_mean"]) - float(v2_ra["completion_mean"])  # type: ignore[index]
    truth_delta = float(v3_ra["truth_delta_pct"])  # type: ignore[index]
    completion_recovered_from_v3_proxy = float(v3_ra["completion_mean"]) - float(  # type: ignore[index]
        v3_proxy["completion_mean"]  # type: ignore[index]
    )
    two_wins = bool(
        cost_gain >= 1.0 and completion_gain >= -0.005 and truth_delta <= 2.0
    )
    # Overall recommendation: among groups that recover completion and keep
    # truth within +2% (excluding the baseline itself), pick the lowest proxy cost.
    candidates: List[Tuple[str, Dict[str, object]]] = []
    for group in GROUP_ORDER:
        if group == "v2_proxy":
            continue
        block = aggregate[group]  # type: ignore[index]
        block_completion = float(block["completion_mean"])  # type: ignore[index]
        block_truth_delta = float(block["truth_delta_pct"])  # type: ignore[index]
        block_cost_gain = -float(block["proxy_cost_delta_pct"])  # type: ignore[index]
        if (
            block_completion >= base_completion - 0.005
            and (
                block_completion - base_completion >= 0.01 or block_cost_gain >= 1.0
            )
            and block_truth_delta <= 2.0
        ):
            candidates.append((group, block))
    if two_wins:
        recommended = "v3_route_aware"
        reason = (
            "v3 + route_aware 同时满足：proxy cost 优于 v2/proxy "
            f"（{cost_gain:+.2f}%）、completion 不回退（{completion_gain:+.4f}）、"
            f"truth_v2 变化 {truth_delta:+.2f}%。这是 P2.17 想要的\"两全\"组合。"
        )
    elif candidates:
        recommended = min(
            candidates, key=lambda item: float(item[1]["proxy_cost_mean"])  # type: ignore[index]
        )[0]
        reason = (
            "v3 + route_aware 不是严格两全：它把 completion 从 v3/proxy 的 "
            f"{v3_proxy['completion_mean']} 拉回到 {v3_ra['completion_mean']}"  # type: ignore[index]
            f"（{completion_recovered_from_v3_proxy:+.4f}），proxy cost 仍比 baseline 好 "
            f"{cost_gain:+.2f}%；但它比 v2/route_aware 的 completion 低 "
            f"{abs(completion_vs_v2ra):.4f}，且 truth_v2 {truth_delta:+.2f}% 超过 +2% 容忍。"
            f"综合 completion + truth 约束，推荐 {GROUP_LABELS[recommended]}。"
        )
    else:
        recommended = "v2_proxy"
        reason = (
            "v3 + route_aware 没有带来稳定的两全收益，且各组合都没有同时满足 "
            "completion 恢复与 truth +2% 约束；保守推荐保持 v2/proxy 基线。"
        )
    options: Dict[str, object] = {
        "completion_first": {
            "group": "route_aware_repair",
            "proxy_cost_mean": repair["proxy_cost_mean"],
            "truth_v2_mean": repair["truth_v2_mean"],
            "completion_mean": repair["completion_mean"],
            "fully_routed": repair["fully_routed"],
            "runtime_s_mean": repair["runtime_s_mean"],
            "note": "最高 completion + truth 不劣化，但允许最多 60 次 router 调用，最慢。",
        },
        "no_router_calls_balanced": {
            "group": "v2_route_aware",
            "proxy_cost_mean": v2_ra["proxy_cost_mean"],
            "truth_v2_mean": v2_ra["truth_v2_mean"],
            "completion_mean": v2_ra["completion_mean"],
            "fully_routed": v2_ra["fully_routed"],
            "runtime_s_mean": v2_ra["runtime_s_mean"],
            "note": "不调用 router 的平衡选项：completion 最高 0.9755，proxy cost 与 baseline 持平。",
        },
        "min_proxy_cost": {
            "group": "v3_route_aware",
            "proxy_cost_mean": v3_ra["proxy_cost_mean"],
            "truth_v2_mean": v3_ra["truth_v2_mean"],
            "completion_mean": v3_ra["completion_mean"],
            "fully_routed": v3_ra["fully_routed"],
            "runtime_s_mean": v3_ra["runtime_s_mean"],
            "note": "proxy cost 最低（-2.63%），但 completion 只有 0.9100、truth +3.19%。",
        },
    }
    return {
        "question": "v3 + route_aware 能否同时拿到 cost 与 completion 收益？",
        "two_wins": two_wins,
        "v3_route_aware": {
            "proxy_cost_gain_pct": round(cost_gain, 2),
            "truth_delta_pct": round(truth_delta, 2),
            "completion_gain": round(completion_gain, 4),
            "completion_vs_v2_route_aware": round(completion_vs_v2ra, 4),
            "completion_recovered_from_v3_proxy": round(
                completion_recovered_from_v3_proxy, 4
            ),
            "fully_routed": v3_ra["fully_routed"],
        },
        "v3_vs_v2_under_route_aware": {
            "v3_lower_proxy_cost": bool(
                float(v3_ra["proxy_cost_mean"]) < float(v2_ra["proxy_cost_mean"])  # type: ignore[index]
            ),
            "v3_higher_completion": bool(completion_vs_v2ra > 0.0),
            "v3_proxy_cost_mean": v3_ra["proxy_cost_mean"],
            "v2_proxy_cost_mean": v2_ra["proxy_cost_mean"],
            "v3_completion_mean": v3_ra["completion_mean"],
            "v2_completion_mean": v2_ra["completion_mean"],
        },
        "v3_proxy_reference": {
            "proxy_cost_mean": v3_proxy["proxy_cost_mean"],
            "completion_mean": v3_proxy["completion_mean"],
            "note": "pure-proxy v3: better cost, worse completion (P2.16 issue).",
        },
        "repair_variant": {
            "group": "route_aware_repair",
            "completion_mean": repair["completion_mean"],
            "proxy_cost_mean": repair["proxy_cost_mean"],
            "truth_v2_mean": repair["truth_v2_mean"],
            "runtime_s_mean": repair["runtime_s_mean"],
        },
        "options": options,
        "recommended_group": recommended,
        "recommended_label": GROUP_LABELS[recommended],
        "reason": reason,
        "note": (
            "Recommendation is computed deterministically from the benchmark rows; "
            "metrics are offline surrogates (proxy cost / hidden pseudo-physics truth / "
            "1 mm 2-layer grid-maze router)."
        ),
    }


def write_solver_combo_report(
    data: Dict[str, object],
    out_dir: Optional[pathlib.Path] = None,
) -> Tuple[pathlib.Path, pathlib.Path]:
    """Write ``report_solver_combo.md`` / ``.json`` and return their paths."""
    directory = pathlib.Path(out_dir) if out_dir is not None else PROJECT_ROOT
    directory.mkdir(parents=True, exist_ok=True)
    json_path = directory / REPORT_JSON
    md_path = directory / REPORT_MD
    json_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

    config = data["config"]  # type: ignore[index]
    aggregate = data["aggregate"]  # type: ignore[index]
    per_template = aggregate["per_template"]  # type: ignore[index]
    conclusion = data["conclusion"]  # type: ignore[index]
    base = aggregate["v2_proxy"]
    lines: List[str] = []
    lines.append("# P2.17：solver_v3 + route-aware 组合实验\n")
    lines.append(
        f"- 配置：{len(config['templates'])} 模板 × seeds {config['seeds']}，"
        f"所有求解组同预算 steps={config['steps']}；route-aware 固定 "
        f"w_route={config['route_aware_weight']}；repair 变体 max_routes={config['max_routes']}"
    )
    lines.append(
        f"- 运行：{aggregate['n_runs_per_group']} runs/组 × {aggregate['n_groups']} 组；"
        f"总耗时 {data['runtime_s']} s；router = {config['router']}；truth = {config['truth']}\n"
    )
    lines.append("## 一、五组汇总（8 模板 × seeds 0/1 均值，baseline = v2/proxy）\n")
    lines.append(
        "| 组别 | proxy cost | cost Δ% | truth_v2 | truth Δ% | completion | completion Δ | "
        "全布通 | 硬可行率 | 耗时 (s) |"
    )
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for group in GROUP_ORDER:
        block = aggregate[group]
        lines.append(
            f"| {GROUP_LABELS[group]} | {block['proxy_cost_mean']} | "
            f"{block['proxy_cost_delta_pct']:+.2f}% | {block['truth_v2_mean']} | "
            f"{block['truth_delta_pct']:+.2f}% | {block['completion_mean']} | "
            f"{block['completion_delta']:+.4f} | {block['fully_routed']} | "
            f"{block['hard_feasible_rate']:.0%} | {block['runtime_s_mean']} |"
        )
    lines.append("")
    lines.append("## 二、逐模板：proxy cost / router completion\n")
    lines.append(
        "| 模板 | v2/proxy c/comp | v3/proxy c/comp | v2/ra c/comp | v3/ra c/comp | "
        "ra+repair c/comp | 最低 cost 组 |"
    )
    lines.append("|---|---|---|---|---|---|---|")
    for name in config["templates"]:
        block = per_template[name]
        cells = []
        for group in GROUP_ORDER:
            entry = block[group]
            cells.append(f"{entry['proxy_cost_mean']} / {entry['completion_mean']}")
        lines.append(
            f"| {name} | " + " | ".join(cells) + f" | {block['best_by_cost']} |"
        )
    lines.append("")
    lines.append("## 三、结论：v3 + route_aware 是否\"两全\"？\n")
    combo = conclusion["v3_route_aware"]
    compare = conclusion["v3_vs_v2_under_route_aware"]
    lines.append(
        f"- **两全判定：{conclusion['two_wins']}**。v3/route_aware 相对 v2/proxy："
        f"proxy cost {combo['proxy_cost_gain_pct']:+.2f}%（正=更好）、"
        f"completion {combo['completion_gain']:+.4f}、truth_v2 {combo['truth_delta_pct']:+.2f}%；"
        f"全布通 {combo['fully_routed']}。"
    )
    lines.append(
        f"- **部分修复**：v3/route_aware 把 completion 从 v3/proxy 的 "
        f"{conclusion['v3_proxy_reference']['completion_mean']} 拉回 "
        f"{compare['v3_completion_mean']}（{combo['completion_recovered_from_v3_proxy']:+.4f}），"
        f"同时 proxy cost 仍比 baseline 好 {combo['proxy_cost_gain_pct']:+.2f}%；"
        "说明 route-aware 目标确实缓解了 P2.16 的可布通性回退。"
    )
    lines.append(
        f"- 但同一 route-aware 目标下 v3 vs v2：v3 的 proxy cost 更低 = "
        f"{compare['v3_lower_proxy_cost']}（{compare['v3_proxy_cost_mean']} vs "
        f"{compare['v2_proxy_cost_mean']}），completion 更高 = "
        f"{compare['v3_higher_completion']}（{compare['v3_completion_mean']} vs "
        f"{compare['v2_completion_mean']}）——v3 的 completion 仍比 v2 低 "
        f"{abs(combo['completion_vs_v2_route_aware']):.4f}，且 truth_v2 "
        f"{combo['truth_delta_pct']:+.2f}% 超过 +2%，因此**不是严格两全**。"
    )
    lines.append(
        f"- 对照：v3/proxy 的 proxy cost {conclusion['v3_proxy_reference']['proxy_cost_mean']}、"
        f"completion {conclusion['v3_proxy_reference']['completion_mean']}"
        "（P2.16 的 cost 更好但 completion 更差）。"
    )
    repair = conclusion["repair_variant"]
    lines.append(
        f"- repair 变体：completion {repair['completion_mean']}、proxy cost "
        f"{repair['proxy_cost_mean']}、truth {repair['truth_v2_mean']}、"
        f"耗时 {repair['runtime_s_mean']} s（最高 completion 且 truth 不劣化，但最慢）。\n"
    )
    lines.append("## 四、推荐组合\n")
    lines.append(
        f"- **综合推荐：{conclusion['recommended_label']}**"
        f"（`{conclusion['recommended_group']}`）。"
    )
    lines.append(f"- 理由：{conclusion['reason']}")
    options = conclusion["options"]
    lines.append("- 按优先级备选：")
    lines.append(
        f"  - completion 优先：`{options['completion_first']['group']}` —— completion "
        f"{options['completion_first']['completion_mean']}、truth "
        f"{options['completion_first']['truth_v2_mean']}、proxy cost "
        f"{options['completion_first']['proxy_cost_mean']}、耗时 "
        f"{options['completion_first']['runtime_s_mean']} s（{options['completion_first']['note']}）"
    )
    lines.append(
        f"  - 零 router 调用的平衡选项：`{options['no_router_calls_balanced']['group']}` —— completion "
        f"{options['no_router_calls_balanced']['completion_mean']}、truth "
        f"{options['no_router_calls_balanced']['truth_v2_mean']}、proxy cost "
        f"{options['no_router_calls_balanced']['proxy_cost_mean']}、耗时 "
        f"{options['no_router_calls_balanced']['runtime_s_mean']} s"
    )
    lines.append(
        f"  - proxy cost 优先：`{options['min_proxy_cost']['group']}` —— proxy cost "
        f"{options['min_proxy_cost']['proxy_cost_mean']}、completion "
        f"{options['min_proxy_cost']['completion_mean']}、truth "
        f"{options['min_proxy_cost']['truth_v2_mean']}"
    )
    lines.append(f"\n> {conclusion['note']}\n")
    lines.append("## 五、边界\n")
    lines.append(
        "- 纯离线代理：proxy cost 为工程权重目标，truth_v2 为隐藏离线伪物理模型，"
        "router 为 1 mm/2 层网格迷宫 oracle；不是 DRC/真实可布通证明，"
        "真实布线/DRC/SI/PI/热仍 `NOT RUN`。"
    )
    lines.append(
        "- 所有非 repair 组共享同一 steps 移动预算；repair 组额外允许最多 "
        f"{config['max_routes']} 次 router 调用，因此其耗时不可与其它组直接等价比较。"
    )
    lines.append(
        "- `route_opt.repair_routes` 内部以 solver_v2 重新求解后再做可布通修复，"
        "所以 repair 组不是\"v3 起点 + repair\"，而是当前接口下可用的 P2.5 post-hoc 路径。"
    )
    md_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[combo] wrote {md_path} / {json_path}")
    return md_path, json_path


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="solver_v3 x route-aware combination benchmark")
    parser.add_argument("--seeds", default="0,1")
    parser.add_argument("--steps", type=int, default=DEFAULT_STEPS)
    parser.add_argument("--quick", action="store_true", help="2 templates x 1 seed x 200 steps")
    parser.add_argument("--out", default=str(PROJECT_ROOT))
    args = parser.parse_args(argv)
    seeds = tuple(int(part) for part in args.seeds.split(",") if part.strip())
    if args.quick:
        data = run_benchmark(names=list(template_names())[:2], seeds=seeds[:1], steps=200)
    else:
        data = run_benchmark(seeds=seeds, steps=args.steps)
    write_solver_combo_report(data, pathlib.Path(args.out))
    return 0



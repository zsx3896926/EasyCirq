#!/usr/bin/env python3
"""Minimal Gerber (RS-274X) + Excellon writer, and a reader that proves the round trip (GAPS D3, offline half).

This is deliberately labelled, because it matters:

  **It writes a syntactically valid RS-274X / Excellon pair from a plan, and it can read them back and
  prove the counts match the plan.  It is NOT a CAM-verified output**: no DRC, no aperture-to-pad
  comparison against the real footprints, no panelisation, no fab-specific quirks.  Sending these files to
  a board house without the EDA's own export (and its DRC) would be reckless.

What it does buy: the "from plan to manufacturing files" step stops being a blank, and any regression in
the plan (a missing layer, a floating net, a vanished via) becomes visible in a file the reader checks.

Usage
-----
    python easycirq/scripts/layout/gerber.py write  --dump d.json --plan p.json --out-dir out/gbr
    python easycirq/scripts/layout/gerber.py verify --dump d.json --plan p.json --out-dir out/gbr
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from dfm import components, pad_of  # noqa: E402

MIL_PER_INCH = 1000.0


def _in(mil):
    """mil -> inches at 4 decimals (FSLAX24), the resolution the header declares."""
    return round(float(mil) / MIL_PER_INCH, 4)


def _fmt(mil):
    return "%d" % int(round(float(mil) / MIL_PER_INCH * 10000.0))


def layer_files(layers):
    return {"L%d" % n: "copper-L%d.gbr" % n for n in layers}


def write(dump, plan, out_dir, layers=4):
    """Write copper Gerbers (one per layer), an Excellon drill file and a manifest.  Returns the paths."""
    os.makedirs(out_dir, exist_ok=True)
    r = dump.get("result") or dump
    paths = {}

    # apertures: D10.. for track widths, D20.. for pad/via sizes
    widths = sorted({round(float(t["width"]), 3) for t in plan.get("tracks") or []})
    sizes = set()
    for v in plan.get("vias") or []:
        sizes.add(round(float(v.get("diameter") or v.get("size") or 24.0), 3))
    for c in components(dump):
        for i, raw in enumerate(c.get("pads") or []):
            p = pad_of(raw, i)
            if p["w"] and p["h"] and abs(p["w"] - p["h"]) < 1e-6:
                sizes.add(round(p["w"], 3))
    widths = sorted(widths)
    sizes = sorted(sizes)
    ap_w = {w: 10 + i for i, w in enumerate(widths)}
    ap_s = {s: 20 + i for i, s in enumerate(sizes)}

    for lay in range(1, layers + 1):
        name = layer_files(range(1, layers + 1))["L%d" % lay]
        path = os.path.join(out_dir, name)
        lines = ["G04 RetroCam-02 layer L%d - generated by tools/layout/gerber.py*" % lay,
                 "%FSLAX24Y24*%", "%MOIN*%", "G04 apertures*",
                 "%ADD10C,0.0010*%" if not widths else ""]
        lines = [l for l in lines if l]
        for w, d in ap_w.items():
            lines.append("%%ADD%dC,%.4f*%%" % (d, _in(w)))
        for s, d in ap_s.items():
            lines.append("%%ADD%dC,%.4f*%%" % (d, _in(s)))
        lines.append("G01*")
        # tracks on this layer
        for t in plan.get("tracks") or []:
            if int(t["layer"]) != lay:
                continue
            d = ap_w.get(round(float(t["width"]), 3))
            if d is None:
                continue
            lines.append("D%d*" % d)
            lines.append("X%sY%sD02*" % (_fmt(t["x1"]), _fmt(t["y1"])))
            lines.append("X%sY%sD01*" % (_fmt(t["x2"]), _fmt(t["y2"])))
        # pads on this layer (SMD on their own layer, through-hole everywhere)
        for c in components(dump):
            for i, raw in enumerate(c.get("pads") or []):
                p = pad_of(raw, i)
                on = p["layer"] == 12 or lay == 1 or p["drill"] > 0
                if not on:
                    continue
                d = ap_s.get(round(max(p["w"], p["h"]), 3))
                if d is None:
                    continue
                lines.append("D%d*" % d)
                lines.append("X%sY%sD03*" % (_fmt(p["x"]), _fmt(p["y"])))
        # vias are flashed on every copper layer
        for v in plan.get("vias") or []:
            d = ap_s.get(round(float(v.get("diameter") or 24.0), 3))
            if d is None:
                continue
            lines.append("D%d*" % d)
            lines.append("X%sY%sD03*" % (_fmt(v["x"]), _fmt(v["y"])))
        lines.append("M02*")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
        paths["L%d" % lay] = path

    # Excellon: round drills only.  Slots are NOT emitted - see the note in the file header.
    drills = {}
    for c in components(dump):
        for i, raw in enumerate(c.get("pads") or []):
            p = pad_of(raw, i)
            if p["drill"] > 0:
                drills.setdefault(round(p["drill"], 3), []).append((p["x"], p["y"]))
    for v in plan.get("vias") or []:
        d = float(v.get("drill") or 12.0)
        drills.setdefault(round(d, 3), []).append((v["x"], v["y"]))
    exc = [("G04 RetroCam-02 drill file - generated by tools/layout/gerber.py",
            "G04 slots are NOT emitted (the dump's slot payload is not fab-verified here)"),
           ("M48", "INCH,TZ", "FMAT,2")]
    lines = [l for pair in exc for l in pair]
    tools = sorted(drills)
    for idx, d in enumerate(tools, start=1):
        lines.append("T%dC%.4f" % (idx, _in(d)))
    lines.append("%")
    lines.append("G90")
    lines.append("G05")
    for idx, d in enumerate(tools, start=1):
        lines.append("T%d" % idx)
        for x, y in drills[d]:
            lines.append("X%.4fY%.4f" % (_in(x), _in(y)))
    lines.append("T0")
    lines.append("M30")
    drill_path = os.path.join(out_dir, "drill.drl")
    with open(drill_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    paths["drill"] = drill_path

    # a placement/CPL stub: designator, centre, rotation, layer - the data an assembler needs
    cpl = os.path.join(out_dir, "placement.cpl")
    with open(cpl, "w", encoding="utf-8", newline="\n") as f:
        f.write("Designator,MidX(in),MidY(in),Rotation,Layer\n")
        for c in components(dump):
            f.write("%s,%.4f,%.4f,%.1f,%s\n" % (
                c.get("designator", "?"), _in(c.get("x", 0)), _in(c.get("y", 0)),
                float(c.get("rotation") or 0.0), "T" if int(c.get("layer") or 1) == 1 else "B"))
    paths["cpl"] = cpl

    manifest = {"layers": layers, "gerber": {k: os.path.basename(v) for k, v in paths.items()},
                "tracks": len(plan.get("tracks") or []), "vias": len(plan.get("vias") or []),
                "drill_tools": len(tools),
                "note": "syntactically valid, NOT CAM-verified - run the EDA export and its DRC "
                        "before sending anything to a fabricator"}
    with open(os.path.join(out_dir, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=1)
    paths["manifest"] = os.path.join(out_dir, "manifest.json")
    return paths


def read_gerber(path):
    """(apertures, flashes, draws) - enough to count what a file actually contains."""
    apertures, flashes, draws = {}, 0, 0
    x = y = None
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if line.startswith("%ADD"):
                body = line[4:].split("*")[0]
                code, _, rest = body.partition("C,")
                try:
                    apertures[int(code)] = float(rest)
                except ValueError:
                    pass
            elif line.startswith("D") and line.endswith("*") and line[1:].rstrip("*").isdigit():
                continue
            elif "D03*" in line:
                flashes += 1
            elif "D01*" in line:
                draws += 1
            elif "D02*" in line:
                pass
    return apertures, flashes, draws


def read_drill(path):
    tools, hits = {}, 0
    cur = None
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if line.startswith("T") and "C" in line and line[1].split("C")[0].isdigit():
                name, _, dia = line[1:].partition("C")
                try:
                    tools[int(name)] = float(dia)
                except ValueError:
                    pass
            elif line.startswith("T") and line[1:].isdigit():
                cur = int(line[1:])
            elif line.startswith("X") and "Y" in line:
                hits += 1
    return tools, hits


def verify(dump, plan, out_dir, layers=4):
    """Read the files back and compare against the plan.  Returns (ok, rows)."""
    rows = []
    ok = True
    expected_tracks = len(plan.get("tracks") or [])
    total_draws = 0
    for lay in range(1, layers + 1):
        name = layer_files(range(1, layers + 1))["L%d" % lay]
        path = os.path.join(out_dir, name)
        if not os.path.exists(path):
            rows.append((name, "missing", "FAIL"))
            ok = False
            continue
        _ap, flashes, draws = read_gerber(path)
        total_draws += draws
        rows.append((name, "%d draws, %d flashes" % (draws, flashes), "ok"))
    same = total_draws == expected_tracks
    ok = ok and same
    rows.append(("tracks in all layers", "%d read vs %d in plan" % (total_draws, expected_tracks),
                 "ok" if same else "FAIL"))

    drill_path = os.path.join(out_dir, "drill.drl")
    if not os.path.exists(drill_path):
        rows.append(("drill.drl", "missing", "FAIL"))
        ok = False
    else:
        tools, hits = read_drill(drill_path)
        tht = sum(1 for c in components(dump) for i, raw in enumerate(c.get("pads") or [])
                  if pad_of(raw, i)["drill"] > 0)
        expect_hits = tht + len(plan.get("vias") or [])
        good = hits == expect_hits
        ok = ok and good
        rows.append(("drill.drl", "%d holes (%d tools) vs %d expected" % (hits, len(tools), expect_hits),
                     "ok" if good else "FAIL"))
    return ok, rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("action", choices=("write", "verify"))
    ap.add_argument("--dump", required=True)
    ap.add_argument("--plan", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--layers", type=int, default=4)
    a = ap.parse_args()
    with open(a.dump, encoding="utf-8") as f:
        dump = json.load(f)
    with open(a.plan, encoding="utf-8") as f:
        plan = json.load(f)

    if a.action == "write":
        paths = write(dump, plan, a.out_dir, a.layers)
        print("wrote:")
        for k, v in sorted(paths.items()):
            print("  %-8s %s" % (k, os.path.basename(v)))
        print("\nNOT CAM-verified: run the EDA export and its DRC before a fabricator sees these files.")
        return 0

    ok, rows = verify(dump, plan, a.out_dir, a.layers)
    print("| artefact | read back | verdict |")
    print("|---|---|---|")
    for name, detail, verdict in rows:
        print("| %s | %s | %s |" % (name, detail, verdict))
    print("\nround trip: %s" % ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())

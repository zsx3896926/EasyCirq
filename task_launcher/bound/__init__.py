"""Zhigou B1-Bound — read-only binding layer on top of B1's task launcher.

This package is the **capability surface** half of the B1 PoC: instead of only
telling the model to follow a procedure, it removes the tools that could bypass
it and keeps execution, read-back, evidence and the final report inside a
trusted supervisor process.

Layout (all new files; B1's ``task_launcher`` modules are *read-only reuse only*
and are deliberately not imported here)::

    task_launcher/bound/
        __init__.py      version, schema ids, states, error codes, constants
        __main__.py      ``python -m task_launcher.bound serve|plan|run|selftest``
        cli.py           argument parsing / sub-commands
        config.py        per-task configuration, path and limit validation
        errors.py        stable error codes
        schema.py        strict JSON-Schema-subset validation (stdlib only)
        state.py         task state machine (tool -> precondition -> next state)
        receipts.py      canonical JSON + HMAC-SHA256 receipt chain
        backends.py      EdaBackend interface, fixture backend, Phase-2 stubs
        tools.py         MCP tool specs (strict input schemas)
        supervisor.py    MCP stdio JSON-RPC server (trusted process)
        report.py        server-generated final report
        runner.py        hardened Claude Code argv / task artifact generation
        settings.py      per-task settings.json (deny / allow / optional hooks)
        b1.py            optional B1 integration probe (BLOCKED ON B1)
        selftest.py      offline adversarial self-check
        hooks/           optional Phase-3 hook scripts (disabled by default)
        fixtures/        frozen synthetic snapshot + audit cases (no EDA)

Hard boundaries of this phase:

* read-only: Phase 1 tools can only start, read a supervisor-owned snapshot,
  run offline audits, emit evidence and finalize; no write tool exists;
* no EDA, no daemon, no connector, no network: the fixture backend reports
  ``real_eda: "NOT RUN"`` and ``eda_calls: 0``;
* the HMAC key only lives in the supervisor process memory and is never written
  to disk, argv, settings, hooks or the agent environment;
* the final report is generated by the supervisor (``report.py``) from signed
  receipts; model text never becomes a verdict.
"""


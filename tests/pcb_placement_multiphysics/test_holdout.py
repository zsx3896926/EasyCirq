"""Tests for the P2.10 holdout validation ``mp_place.holdout``.

Run with::

    python -m unittest tests.test_holdout -v

Guards: holdout protocol determinism, strict seed isolation (tuning seeds 0/1
vs holdout seeds 2/3/4, and the tuner is never invoked), report structure, and
the deterministic safe-default recommendation logic.  The full 8 templates x
3 seeds experiment is generated by ``python -m mp_place.holdout`` into
``report_holdout.{md,json}``; tests use small step budgets for speed.
"""

import json
import tempfile
import unittest
from pathlib import Path
from unittest import mock

import mp_place.route_cost as route_cost
from mp_place.holdout import (
    HOLDOUT_SEEDS,
    TUNING_SEEDS,
    assert_seed_protocol,
    recommend_safe_default,
    run_holdout,
    tuned_table_digest,
    write_holdout_report,
)


def _strip_timings(value):
    """Recursively drop wall-clock fields so two runs can be compared."""
    if isinstance(value, dict):
        return {
            key: _strip_timings(item)
            for key, item in value.items()
            if key != "runtime_s"
        }
    if isinstance(value, list):
        return [_strip_timings(item) for item in value]
    return value


def _mini_run(**overrides):
    params = dict(
        names=("buck",),
        holdout_seeds=(2,),
        steps=120,
        intent_steps=120,
    )
    params.update(overrides)
    return run_holdout(**params)


class ProtocolTests(unittest.TestCase):
    def test_tuning_and_holdout_seeds_are_disjoint(self):
        self.assertFalse(set(TUNING_SEEDS) & set(HOLDOUT_SEEDS))
        self.assertEqual(tuple(TUNING_SEEDS), (0, 1))
        self.assertEqual(tuple(HOLDOUT_SEEDS), (2, 3, 4))
        assert_seed_protocol()  # default protocol must pass

    def test_seed_isolation_guard_rejects_overlap(self):
        with self.assertRaises(ValueError):
            assert_seed_protocol((0, 1), (1, 2))
        with self.assertRaises(ValueError):
            assert_seed_protocol((0, 1), ())
        with self.assertRaises(ValueError):
            run_holdout(
                names=("buck",),
                holdout_seeds=(0,),
                steps=40,
                include_intent=False,
            )

    def test_holdout_protocol_is_deterministic(self):
        first = _mini_run()
        second = _mini_run()
        self.assertEqual(_strip_timings(first), _strip_timings(second))
        self.assertEqual(
            first["protocol"]["tuned_table_digest"], tuned_table_digest()
        )
        self.assertEqual(first["protocol"]["tuning_seeds"], [0, 1])
        self.assertEqual(first["protocol"]["holdout_seeds"], [2])

    def test_tuner_is_never_invoked_on_the_holdout(self):
        def _forbidden(*_args, **_kwargs):
            raise AssertionError("holdout must not re-run the route_cost tuner")

        with mock.patch.object(route_cost, "tune_template", _forbidden), mock.patch.object(
            route_cost, "tune_all", _forbidden
        ):
            data = _mini_run(include_intent=False)
        self.assertEqual(data["schema"], "mp_place.holdout/v1")
        self.assertIsNone(data["intent"])
        # The frozen P2.9 table is evaluated as-is.
        self.assertEqual(
            data["protocol"]["tuned_table"]["buck"],
            route_cost.TUNED_TABLE["buck"],
        )


class ReportStructureTests(unittest.TestCase):
    def test_report_schema_markdown_and_json(self):
        data = _mini_run()
        self.assertEqual(data["schema"], "mp_place.holdout/v1")
        protocol = data["protocol"]
        self.assertIn("tuning_seeds", protocol)
        self.assertIn("holdout_seeds", protocol)
        self.assertTrue(protocol["seeds_disjoint"])
        self.assertEqual(protocol["tuning_seeds"], [0, 1])
        route = data["route_cost"]
        self.assertEqual(route["runs"], 3)  # one template x one seed x one triple
        for group in ("baseline", "fixed", "tuned"):
            self.assertIn(group, route["aggregate"])
            self.assertIn(group, route["aggregate"]["per_template"]["buck"])
            self.assertIn("completion_mean", route["aggregate"][group])
            self.assertIn("truth_v2_mean", route["aggregate"][group])
        self.assertIn("targets_met_templates", route["aggregate"])
        intent = data["intent"]
        self.assertIsNotNone(intent)
        self.assertEqual(len(intent["groups"]), 2)
        for group in intent["groups"]:
            self.assertIn("relax", group)
            self.assertIn("ccg_hard_per_run", group)
            self.assertIn("ccg_soft_per_run", group)
            self.assertIn("mean_truth_vs_baseline_pct", group)
            self.assertIn("target_met", group)
        recommendation = data["recommendation"]
        self.assertIn("safe_default", recommendation)
        self.assertIn("per_template_action", recommendation)
        self.assertIn("holdout_tuned_generalises", recommendation)

        with tempfile.TemporaryDirectory() as tmp:
            md_path, json_path = write_holdout_report(data, Path(tmp))
            self.assertTrue(md_path.exists())
            self.assertTrue(json_path.exists())
            loaded = json.loads(json_path.read_text(encoding="utf-8"))
            self.assertEqual(loaded["schema"], "mp_place.holdout/v1")
            text = md_path.read_text(encoding="utf-8")
            for marker in ("调参只用 seeds", "route_cost", "intent", "安全默认"):
                self.assertIn(marker, text)


class RecommendationTests(unittest.TestCase):
    @staticmethod
    def _synthetic(tuned_pass, fixed_pass, baseline_pass, tuned_truth_delta):
        def _met(passes: str, template_index: int) -> bool:
            count = int(passes.split("/")[0])
            return count >= 2 - template_index

        return {
            "templates": ["t1", "t2"],
            "aggregate": {
                "n_templates": 2,
                "targets_met_templates": {
                    "baseline": baseline_pass,
                    "fixed": fixed_pass,
                    "tuned": tuned_pass,
                },
                "tuned": {"truth_delta_pct": tuned_truth_delta},
                "per_template": {
                    "t1": {
                        "selected_tuned": {"w_route": 6.0, "profile": "default"},
                        "targets_met": {
                            "baseline": _met(baseline_pass, 0),
                            "fixed": _met(fixed_pass, 0),
                            "tuned": _met(tuned_pass, 0),
                        },
                    },
                    "t2": {
                        "selected_tuned": {"w_route": 0.0, "profile": "default"},
                        "targets_met": {
                            "baseline": _met(baseline_pass, 1),
                            "fixed": _met(fixed_pass, 1),
                            "tuned": _met(tuned_pass, 1),
                        },
                    },
                },
            },
        }

    def test_fallback_to_fixed_when_tuned_does_not_generalise(self):
        result = self._synthetic("0/2", "2/2", "0/2", 5.0)
        recommendation = recommend_safe_default(result)
        self.assertFalse(recommendation["holdout_tuned_generalises"])
        self.assertEqual(recommendation["safe_default"], "fixed")
        self.assertEqual(
            recommendation["safe_default_config"]["w_route"],
            route_cost.DEFAULT_W_ROUTE,
        )
        self.assertEqual(
            recommendation["per_template_action"]["t1"]["action"],
            "fallback_fixed(w=2.0)",
        )
        self.assertEqual(
            recommendation["per_template_action"]["t2"]["action"],
            "fallback_fixed(w=2.0)",
        )
        self.assertEqual(recommendation, recommend_safe_default(result))

    def test_tuned_is_kept_when_it_generalises(self):
        result = self._synthetic("2/2", "1/2", "1/2", 0.5)
        recommendation = recommend_safe_default(result)
        self.assertTrue(recommendation["holdout_tuned_generalises"])
        self.assertEqual(recommendation["safe_default"], "tuned")
        self.assertIsNone(recommendation["safe_default_config"])

    def test_baseline_default_when_nothing_helps(self):
        result = self._synthetic("0/2", "0/2", "2/2", 3.0)
        recommendation = recommend_safe_default(result)
        self.assertEqual(recommendation["safe_default"], "baseline")
        self.assertEqual(recommendation["safe_default_config"]["w_route"], 0.0)


if __name__ == "__main__":
    unittest.main()

"""Tests for the P2.17 solver_v3 + route-aware combination ``mp_place.solver_combo``.

Run with::

    python -m unittest tests.test_solver_combo -v

The five-group experiment (v2/proxy, v3/proxy, v2/route_aware, v3/route_aware,
route-aware + post-hoc repair; 8 templates x seeds 0/1, steps=800) is generated by
``python -m mp_place.solver_combo`` into ``report_solver_combo.{md,json}``.
These tests are the fast behavioural guards: determinism, hard feasibility,
budget equivalence and an 8-template smoke run.
"""

import math
import unittest

from mp_place.model import hard_violations
from mp_place.objective import ProxyObjective
from mp_place.solver_combo import (
    GROUP_ORDER,
    MAX_ROUTES,
    evaluate_group,
)
from mp_place.templates import instantiate, template_names


def _strip_timings(value):
    """Recursively drop wall-clock fields so two runs can be compared."""
    if isinstance(value, dict):
        return {
            key: _strip_timings(item)
            for key, item in value.items()
            if key != "runtime_s"
        }
    if isinstance(value, list):
        return [_strip_timings(item) for item in value]
    return value


class DeterminismTests(unittest.TestCase):
    def test_each_group_is_deterministic(self):
        scenario = instantiate("buck", seed=3)
        for group in ("v2_proxy", "v3_route_aware", "route_aware_repair"):
            first = evaluate_group(scenario, group, seed=3, steps=100)
            second = evaluate_group(scenario, group, seed=3, steps=100)
            self.assertEqual(
                _strip_timings(first),
                _strip_timings(second),
                group,
            )
            self.assertEqual(first["placement"], second["placement"], group)
            self.assertEqual(first["proxy_cost"], second["proxy_cost"], group)


class FeasibilityTests(unittest.TestCase):
    def test_v3_route_aware_smoke_on_all_templates(self):
        for name in template_names():
            scenario = instantiate(name, seed=1)
            result = evaluate_group(scenario, "v3_route_aware", seed=1, steps=80)
            self.assertTrue(result["feasible"], name)
            self.assertEqual(hard_violations(scenario, result["placement"]), [], name)
            self.assertTrue(math.isfinite(result["proxy_cost"]), name)
            self.assertTrue(math.isfinite(result["truth_v2"]), name)
            self.assertGreaterEqual(result["completion"], 0.0, name)
            self.assertLessEqual(result["completion"], 1.0, name)

    def test_all_groups_feasible_on_one_template(self):
        scenario = instantiate("motor", seed=0)
        for group in GROUP_ORDER:
            result = evaluate_group(scenario, group, seed=0, steps=100)
            self.assertTrue(result["feasible"], group)
            self.assertEqual(
                hard_violations(scenario, result["placement"]), [], group
            )
            self.assertAlmostEqual(
                result["proxy_cost"],
                ProxyObjective(scenario).cost(result["placement"]),
                places=9,
                msg=group,
            )


class BudgetTests(unittest.TestCase):
    def test_solver_groups_share_the_same_move_budget(self):
        scenario = instantiate("motor", seed=0)
        steps = 100
        for group in ("v2_proxy", "v3_proxy", "v2_route_aware", "v3_route_aware"):
            result = evaluate_group(scenario, group, seed=0, steps=steps)
            self.assertEqual(result["attempts"], steps, group)
            self.assertEqual(result["routes_calls"], 0, group)
            solver_stats = result["solver_stats"]
            if group.startswith("v3") or group == "v3_route_aware":
                self.assertEqual(solver_stats["attempts"], steps, group)
                split = solver_stats["budget_split"]
                self.assertEqual(
                    split["greedy_search"] + split["restarts"] + split["polish"],
                    steps,
                    group,
                )
                self.assertEqual(
                    sum(
                        entry["attempts"]
                        for entry in solver_stats["trajectories"]
                    ),
                    steps,
                    group,
                )
            else:
                self.assertEqual(solver_stats["attempts"], steps, group)
                self.assertLessEqual(
                    solver_stats["cost_evals"], steps + solver_stats["restarts"], group
                )

    def test_repair_group_respects_max_routes(self):
        scenario = instantiate("buck", seed=0)
        result = evaluate_group(scenario, "route_aware_repair", seed=0, steps=100)
        self.assertGreaterEqual(result["routes_calls"], 1)
        self.assertLessEqual(result["routes_calls"], MAX_ROUTES)
        self.assertEqual(result["completion"], result["solver_stats"]["final_completion"])


class SmokeTests(unittest.TestCase):
    def test_baseline_and_combo_smoke_on_all_templates(self):
        for name in template_names():
            scenario = instantiate(name, seed=0)
            baseline = evaluate_group(scenario, "v2_proxy", seed=0, steps=80)
            combo = evaluate_group(scenario, "v3_route_aware", seed=0, steps=80)
            self.assertTrue(baseline["feasible"], name)
            self.assertTrue(combo["feasible"], name)
            self.assertGreater(baseline["proxy_cost"], 0.0, name)
            self.assertGreater(combo["proxy_cost"], 0.0, name)
            self.assertTrue(math.isfinite(combo["truth_v2"]), name)


if __name__ == "__main__":
    unittest.main()

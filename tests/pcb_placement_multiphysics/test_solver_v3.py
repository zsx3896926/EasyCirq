"""Tests for the P2.16 portfolio solver v3 ``mp_place.solver_v3``.

Run with::

    python -m unittest tests.test_solver_v3 -v

The 8-template x seeds 0/1 comparison with solver_v2 is generated by
``python -m mp_place.solver_v3`` into ``report_solver_v3.{md,json}``; these tests
are the fast behavioural guards: determinism, hard feasibility, budget
equivalence, greedy-start legality and an 8-template smoke run.
"""

import math
import unittest

from mp_place.model import hard_violations
from mp_place.objective import ProxyObjective
from mp_place.solver_v2 import solve as solve_v2
from mp_place.solver_v3 import greedy_placement, solve_v3
from mp_place.templates import instantiate, template_names


def _strip_timings(value):
    """Recursively drop wall-clock fields so two runs can be compared."""
    if isinstance(value, dict):
        return {
            key: _strip_timings(item)
            for key, item in value.items()
            if key != "runtime_s"
        }
    if isinstance(value, list):
        return [_strip_timings(item) for item in value]
    return value


class GreedyStartTests(unittest.TestCase):
    def test_greedy_start_is_hard_feasible_on_all_templates(self):
        for name in template_names():
            sc = instantiate(name, seed=0)
            placement = greedy_placement(sc)
            self.assertEqual(hard_violations(sc, placement), [], name)
            self.assertTrue(math.isfinite(ProxyObjective(sc).cost(placement)), name)

    def test_greedy_start_is_deterministic(self):
        for name in ("buck", "mcu-min"):
            sc = instantiate(name, seed=1)
            self.assertEqual(greedy_placement(sc), greedy_placement(sc), name)


class DeterminismTests(unittest.TestCase):
    def test_same_seed_same_portfolio(self):
        sc = instantiate("mcu-min", seed=2)
        obj = ProxyObjective(sc)
        first = solve_v3(sc, obj.cost, seed=5, steps=120)
        second = solve_v3(sc, obj.cost, seed=5, steps=120)
        self.assertEqual(first[0], second[0])
        self.assertEqual(first[1], second[1])
        self.assertEqual(_strip_timings(first[2]), _strip_timings(second[2]))


class FeasibilityTests(unittest.TestCase):
    def test_smoke_solve_on_all_templates(self):
        for name in template_names():
            sc = instantiate(name, seed=1)
            obj = ProxyObjective(sc)
            placement, cost, stats = solve_v3(sc, obj.cost, seed=1, steps=100)
            self.assertEqual(hard_violations(sc, placement), [], name)
            self.assertTrue(math.isfinite(cost), name)
            self.assertAlmostEqual(obj.cost(placement), cost, places=9, msg=name)
            self.assertTrue(stats["hard_feasible"], name)
            self.assertEqual(len(stats["trajectories"]), 3, name)
            self.assertIn(
                stats["winner"], {"greedy_search", "restarts", "polish"}, name
            )
            self.assertIn(
                stats["warm_start_source"], {"greedy_search", "restarts"}, name
            )


class BudgetTests(unittest.TestCase):
    def test_total_budget_equals_steps(self):
        sc = instantiate("buck", seed=0)
        obj = ProxyObjective(sc)
        for steps in (0, 1, 10, 100, 400):
            placement, cost, stats = solve_v3(sc, obj.cost, seed=0, steps=steps)
            self.assertTrue(math.isfinite(cost), steps)
            self.assertEqual(stats["steps"], steps)
            self.assertEqual(stats["attempts"], steps, steps)
            self.assertEqual(stats["accepted"] + stats["rejected"], stats["attempts"], steps)
            self.assertEqual(
                sum(entry["attempts"] for entry in stats["trajectories"]), steps, steps
            )
            split = stats["budget_split"]
            self.assertEqual(
                split["greedy_search"] + split["restarts"] + split["polish"], steps, steps
            )
            # Only start placements add cost evaluations on top of the move budget.
            self.assertLessEqual(
                stats["cost_evals"], steps + stats["starts_evaluated"], steps
            )

    def test_budget_matches_solver_v2(self):
        sc = instantiate("motor", seed=0)
        obj = ProxyObjective(sc)
        steps = 200
        _pl2, _c2, stats_v2 = solve_v2(sc, obj.cost, seed=0, steps=steps)
        _pl3, _c3, stats_v3 = solve_v3(sc, obj.cost, seed=0, steps=steps)
        self.assertEqual(stats_v2["attempts"], steps)
        self.assertEqual(stats_v3["attempts"], steps)
        self.assertLessEqual(stats_v2["cost_evals"], steps + stats_v2["restarts"])
        self.assertLessEqual(stats_v3["cost_evals"], steps + stats_v3["starts_evaluated"])


if __name__ == "__main__":
    unittest.main()

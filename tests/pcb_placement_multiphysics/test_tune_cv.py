"""Tests for the P2.12 cross-validated route-cost tuning ``mp_place.tune_cv``.

Run with::

    python -m unittest tests.test_tune_cv -v

Guards: CV protocol determinism, strict seed isolation (tuning 0/1/2 vs
evaluation 3/4), router usage confined to the evaluation helper (selection /
aggregation / recommendation are router-free), the deterministic CV selection
rule, and report structure.  The full 8-template experiment is generated by
``python -m mp_place.tune_cv`` into ``report_tune_cv.{md,json}``; tests use a
small grid and step budget for speed.
"""

import json
import tempfile
import unittest
from pathlib import Path
from unittest import mock

import mp_place.tune_cv as tune_cv
from mp_place.router import GridRouter
from mp_place.tune_cv import (
    BASELINE_CONFIG,
    CV_FOLDS,
    CV_SEEDS,
    EVAL_SEEDS,
    FIXED_CONFIG,
    assert_seed_isolation,
    candidate_grid,
    config_key,
    cv_metrics,
    recommend_cv,
    run_tune_cv,
    select_cv_config,
    write_tune_cv_report,
)

SMALL_GRID = [
    {"w_route": 0.0, "profile": "default"},
    {"w_route": 2.0, "profile": "default"},
]


def _strip_timings(value):
    """Recursively drop wall-clock fields so two runs can be compared."""
    if isinstance(value, dict):
        return {
            key: _strip_timings(item)
            for key, item in value.items()
            if key != "runtime_s"
        }
    if isinstance(value, list):
        return [_strip_timings(item) for item in value]
    return value


def _mini_run(**overrides):
    params = dict(
        names=("buck",),
        tuning_seeds=CV_SEEDS,
        eval_seeds=(3,),
        steps=100,
        grid=SMALL_GRID,
    )
    params.update(overrides)
    return run_tune_cv(**params)


def _synthetic_matrix():
    def record(config, per_seed):
        return {
            "config": config,
            "per_seed": {
                str(seed): {"completion": comp, "truth_v2": truth, "feasible": True}
                for seed, (comp, truth) in per_seed.items()
            },
            "completion_mean": sum(c for c, _t in per_seed.values()) / len(per_seed),
            "truth_mean": sum(t for _c, t in per_seed.values()) / len(per_seed),
        }

    good_a = {"w_route": 1.0, "profile": "default"}
    good_b = {"w_route": 2.0, "profile": "default"}
    bad = {"w_route": 6.0, "profile": "pad_heavy"}
    matrix = {
        config_key(good_a): record(good_a, {0: (1.0, 10.0), 1: (1.0, 10.0), 2: (1.0, 10.0)}),
        config_key(good_b): record(good_b, {0: (1.0, 9.0), 1: (1.0, 9.0), 2: (1.0, 9.0)}),
        config_key(bad): record(bad, {0: (0.5, 1.0), 1: (0.5, 1.0), 2: (1.0, 1.0)}),
    }
    return matrix


class ProtocolTests(unittest.TestCase):
    def test_tuning_and_eval_seeds_are_disjoint(self):
        self.assertEqual(tuple(CV_SEEDS), (0, 1, 2))
        self.assertEqual(tuple(EVAL_SEEDS), (3, 4))
        self.assertFalse(set(CV_SEEDS) & set(EVAL_SEEDS))
        validation = {
            seed for fold in CV_FOLDS for seed in fold["validate"]
        }
        training = {seed for fold in CV_FOLDS for seed in fold["train"]}
        self.assertTrue(validation | training <= set(CV_SEEDS))
        assert_seed_isolation()  # defaults must pass

    def test_seed_isolation_guard_rejects_overlap(self):
        with self.assertRaises(ValueError):
            assert_seed_isolation((0, 1, 2), (2, 3))
        with self.assertRaises(ValueError):
            assert_seed_isolation((0, 1, 2), ())
        with self.assertRaises(ValueError):
            run_tune_cv(
                names=("buck",),
                tuning_seeds=(0, 1, 2),
                eval_seeds=(2, 3),
                steps=60,
                grid=SMALL_GRID,
            )

    def test_cv_protocol_is_deterministic(self):
        first = _mini_run()
        second = _mini_run()
        self.assertEqual(_strip_timings(first), _strip_timings(second))
        self.assertEqual(first["protocol"]["tuning_seeds"], [0, 1, 2])
        self.assertEqual(first["protocol"]["eval_seeds"], [3])
        self.assertEqual(first["router_calls"], second["router_calls"])

    def test_router_only_used_by_the_evaluation_helper(self):
        base_router = GridRouter

        class CountingRouter(base_router):  # type: ignore[misc, valid-type]
            calls = 0

            def route(self, placement, critical_nets=None):
                CountingRouter.calls += 1
                return super().route(placement, critical_nets)

        CountingRouter.calls = 0
        with mock.patch.object(tune_cv, "GridRouter", CountingRouter):
            data = _mini_run()
        expected = (
            len(SMALL_GRID) * len(CV_SEEDS) * 1  # tuning grid x seeds x templates
            + 3 * 1 * 1  # baseline / fixed / cv_tuned x eval seed x template
        )
        self.assertEqual(CountingRouter.calls, expected)
        self.assertEqual(data["router_calls"], expected)

        # Pure helpers must not touch the router at all.
        def _forbidden(*_args, **_kwargs):
            raise AssertionError("router must not be called outside evaluation")

        with mock.patch.object(GridRouter, "route", _forbidden):
            candidate_grid()
            config_key(BASELINE_CONFIG)
            cv_metrics(_synthetic_matrix()[config_key({"w_route": 1.0, "profile": "default"})])
            recommendation = recommend_cv(data)
        self.assertIn("safe_default", recommendation)


class SelectionRuleTests(unittest.TestCase):
    def test_min_truth_among_completion_feasible_is_deterministic(self):
        matrix = _synthetic_matrix()
        first = select_cv_config(matrix)
        second = select_cv_config(matrix)
        self.assertEqual(_strip_timings(first), _strip_timings(second))
        self.assertEqual(first["selected"], {"w_route": 2.0, "profile": "default"})
        self.assertEqual(first["status"], "cv_selected")
        self.assertEqual(first["cv_truth_v2"], 9.0)
        self.assertTrue(first["fold_agreement"])
        self.assertEqual(first["validation_seeds"], [0, 1])

    def test_fallback_to_fixed_when_no_candidate_meets_completion(self):
        matrix = _synthetic_matrix()
        only_bad = {
            key: record
            for key, record in matrix.items()
            if record["config"]["w_route"] == 6.0
        }
        selection = select_cv_config(only_bad)
        self.assertEqual(selection["status"], "fallback_fixed_no_cv_candidate")
        self.assertEqual(selection["selected"], FIXED_CONFIG)
        self.assertEqual(selection["feasible_candidates"], 0)


class ReportStructureTests(unittest.TestCase):
    def test_report_schema_markdown_and_json(self):
        data = _mini_run()
        self.assertEqual(data["schema"], "mp_place.tune_cv/v1")
        protocol = data["protocol"]
        for key in ("tuning_seeds", "eval_seeds", "folds", "candidate_grid", "targets"):
            self.assertIn(key, protocol)
        cv = data["cv"]["per_template"]["buck"]
        for key in (
            "selected",
            "selected_key",
            "status",
            "cv_completion",
            "cv_truth_v2",
            "fold_agreement",
            "candidates",
            "matrix",
        ):
            self.assertIn(key, cv)
        aggregate = data["evaluation"]["aggregate"]
        for group in ("baseline", "fixed", "cv_tuned"):
            self.assertIn(group, aggregate)
            self.assertIn(group, aggregate["per_template"]["buck"])
            self.assertIn("completion_mean", aggregate[group])
            self.assertIn("truth_v2_mean", aggregate[group])
        self.assertIn("targets_met_templates", aggregate)
        recommendation = data["recommendation"]
        for key in (
            "cv_generalises",
            "safe_default",
            "disable_p29_tuned_table",
            "reason",
        ):
            self.assertIn(key, recommendation)

        with tempfile.TemporaryDirectory() as tmp:
            md_path, json_path = write_tune_cv_report(data, Path(tmp))
            self.assertTrue(md_path.exists())
            self.assertTrue(json_path.exists())
            loaded = json.loads(json_path.read_text(encoding="utf-8"))
            self.assertEqual(loaded["schema"], "mp_place.tune_cv/v1")
            text = md_path.read_text(encoding="utf-8")
            for marker in ("2-fold CV", "baseline", "fixed", "安全默认"):
                self.assertIn(marker, text)


class RecommendationTests(unittest.TestCase):
    @staticmethod
    def _synthetic(cv_pass, fixed_pass, baseline_pass, truth_delta):
        return {
            "evaluation": {
                "aggregate": {
                    "n_templates": 2,
                    "targets_met_templates": {
                        "baseline": baseline_pass,
                        "fixed": fixed_pass,
                        "cv_tuned": cv_pass,
                    },
                    "cv_tuned": {"truth_delta_pct": truth_delta},
                }
            }
        }

    def test_recommend_safe_default_when_cv_fails(self):
        recommendation = recommend_cv(self._synthetic("0/2", "1/2", "0/2", 4.0))
        self.assertFalse(recommendation["cv_generalises"])
        self.assertEqual(recommendation["safe_default"], "route_aware_fixed")
        self.assertTrue(recommendation["disable_p29_tuned_table"])
        self.assertEqual(recommendation["safe_default_config"], FIXED_CONFIG)
        self.assertEqual(
            recommendation, recommend_cv(self._synthetic("0/2", "1/2", "0/2", 4.0))
        )

    def test_recommend_keeps_cv_when_it_generalises(self):
        recommendation = recommend_cv(self._synthetic("2/2", "1/2", "1/2", 0.3))
        self.assertTrue(recommendation["cv_generalises"])
        self.assertEqual(recommendation["safe_default"], "cv_tuned")
        self.assertFalse(recommendation["disable_p29_tuned_table"])


if __name__ == "__main__":
    unittest.main()

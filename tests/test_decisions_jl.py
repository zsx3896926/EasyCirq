def render(rows, columns=None):
    columns = COLUMNS if columns is None else columns
    lines = [
        "# 测试资产索引",
        "",
        "| " + " | ".join(columns) + " |",
        "|" + "---|" * len(columns),
    ]
    for item in rows:
        lines.append("| " + " | ".join(item[name] for name in columns) + " |")
    return "\n".join(lines) + "\n"


def run_cli(text="default", register=None, args=None):
    with tempfile.TemporaryDirectory() as temp:
        if args is not None:
            command = [sys.executable, str(SCRIPT)] + list(args)
        else:
            if text == "default":
                text = render([row(), second_row()])
            path = Path(temp) / "index.md"
            if text is not None:
                path.write_text(text, encoding="utf-8")
            command = [
                sys.executable, str(SCRIPT), str(path),
                "--source-register", str(register or REGISTER),
                "--root", str(ROOT),
            ]
        result = subprocess.run(command, capture_output=True, text=True,
                                encoding="utf-8")
    return result


def payload(result):
    return json.loads(result.stdout)


def codes(result):
    return {item["code"] for item in payload(result)["findings"]}


def frontmatter(text):
    end = text.find("\n---", 4)
    data = {}
    for line in text[4:end].splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            data[key.strip()] = value.strip()
    return data


def section(text, heading):
    start = text.index(heading)
    nxt = text.find("\n## ", start + len(heading))
    return text[start:] if nxt < 0 else text[start:nxt]


def registered_ids():
    text = REGISTER.read_text(encoding="utf-8")
    return set(re.findall(r"^\|\s*([A-Z][A-Z0-9]*-[A-Z0-9]+)\s*\|", text,
                          flags=re.MULTILINE))


